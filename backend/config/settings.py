def _env(key, default=None, cast=None):
    """Read env var from process environment first, then backend/.env."""
    raw = os.environ.get(key)
    if raw is None and _ENV_FILE.is_file():
        try:
            file_cfg = Config(RepositoryEnv(str(_ENV_FILE)))
            kwargs = {'default': default}
            if cast is not None:
                kwargs['cast'] = cast
            return file_cfg(key, **kwargs)
        except (PermissionError, OSError):
            pass
    if raw is None:
        if cast is bool:
            if default is not None:
                return default
            return False
        return default
    if cast is bool:
        return str(raw).strip().lower() in ('1', 'true', 'yes', 'on')
    if cast is not None:
        return cast(raw)
    return raw


config = _env


def _build_databases():
    """
    Priority:
    1. DATABASE_URL (VPS, Render, production)
    2. DB_NAME + DB_USER + … (optional local PostgreSQL without a URL)
    3. SQLite file in backend/ (dev fallback when nothing is configured)
    """
    database_url = config('DATABASE_URL', default='').strip()
    if database_url.startswith('postgres'):
        host = (urlparse(database_url).hostname or '').lower()
        ssl_require = host not in ('localhost', '127.0.0.1')
        return {
            'default': dj_database_url.config(
                default=database_url,
                conn_max_age=600,
                conn_health_checks=True,
                ssl_require=ssl_require,
            )
        }

    db_name = config('DB_NAME', default='').strip()
    if db_name:
        return {
            'default': {
                'ENGINE': 'django.db.backends.postgresql',
                'NAME': db_name,
                'USER': config('DB_USER', default='postgres'),
                'PASSWORD': config('DB_PASSWORD', default=''),
                'HOST': config('DB_HOST', default='localhost'),
                'PORT': config('DB_PORT', default='5432'),
                'OPTIONS': {'client_encoding': 'UTF8'},
            }
        }

    return {
        'default': dj_database_url.config(
            default=f'sqlite:///{BASE_DIR / "db.sqlite3"}',
        )
    }


